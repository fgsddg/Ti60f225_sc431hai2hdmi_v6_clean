#!/usr/bin/env python3
"""Generate the 16x16 Chinese glyph ROM and a preview for the style HUD."""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = Path(r"C:/Windows/Fonts/simhei.ttf")
CHARS = "强度调节：开启关闭"
GLYPH_SIZE = 16


def glyph_bitmap(char: str) -> list[int]:
    font = ImageFont.truetype(str(FONT), 16)
    image = Image.new("L", (GLYPH_SIZE, GLYPH_SIZE), 0)
    draw = ImageDraw.Draw(image)
    bbox = draw.textbbox((0, 0), char, font=font)
    x = (GLYPH_SIZE - (bbox[2] - bbox[0])) // 2 - bbox[0]
    y = (GLYPH_SIZE - (bbox[3] - bbox[1])) // 2 - bbox[1]
    draw.text((x, y), char, fill=255, font=font)
    rows = []
    for row in range(GLYPH_SIZE):
        bits = 0
        for col in range(GLYPH_SIZE):
            bits = (bits << 1) | (1 if image.getpixel((col, row)) >= 96 else 0)
        rows.append(bits)
    return rows


def main() -> int:
    glyphs = [glyph_bitmap(ch) for ch in CHARS]
    lines = [
        "/* Auto-generated by tools/gen_style_hud_font.py. */",
        "`timescale 1ns / 1ps",
        "",
        "module style_hud_glyph_rom (",
        "    input  wire [3:0]   idx,",
        "    output reg  [255:0] bits",
        ");",
        "    always @* begin",
        "        case (idx)",
    ]
    for index, rows in enumerate(glyphs):
        value = "".join(f"{row:04X}" for row in rows)
        lines.append(f"            4'd{index}: bits = 256'h{value};")
    lines += [
        "            default: bits = 256'd0;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    output = ROOT / "rtl" / "scale" / "style_hud_font.v"
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    scale = 8
    margin = 8
    cell = 18
    width = margin * 2 + len(CHARS) * cell
    preview = Image.new("RGB", (width, GLYPH_SIZE * scale + margin * 2 + 20), (16, 16, 16))
    draw = ImageDraw.Draw(preview)
    for index, rows in enumerate(glyphs):
        x0 = margin + index * cell
        for y, bits in enumerate(rows):
            for x in range(GLYPH_SIZE):
                if bits & (0x8000 >> x):
                    draw.rectangle(
                        (x0 + x * scale, margin + y * scale,
                         x0 + (x + 1) * scale - 1, margin + (y + 1) * scale - 1),
                        fill=(255, 255, 255),
                    )
        draw.text((x0, GLYPH_SIZE * scale + margin), CHARS[index],
                  fill=(180, 220, 255), font=ImageFont.truetype(str(FONT), 14))
    preview_path = ROOT / "outflow_keys" / "style_hud_font_preview.png"
    preview_path.parent.mkdir(parents=True, exist_ok=True)
    preview.save(preview_path)
    print(f"wrote {output}")
    print(f"wrote {preview_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())